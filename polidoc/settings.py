def _margen_env(nombre, defecto):
    """Margen en pulgadas desde el entorno; cadena vacía → None (no tocar)."""
    valor = os.getenv(nombre, str(defecto)).strip()
    if not valor:
        return None
    try:
        return float(valor)
    except ValueError:
        return defecto


