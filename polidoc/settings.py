# SQLite timeout for concurrency (WAL mode DISABLED - causes corruption with Docker bind mounts)
if 'sqlite' in os.getenv('DB_ENGINE', 'django.db.backends.sqlite3'):
    from django.db.backends.signals import connection_created

    def enable_sqlite_options(sender, connection, **kwargs):
        if connection.vendor == 'sqlite':
            try:
                cursor = connection.cursor()
                cursor.execute('PRAGMA busy_timeout=30000;')
            except Exception:
                pass

    connection_created.connect(enable_sqlite_options)


